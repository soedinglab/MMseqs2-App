#!/usr/bin/env node
// Build the minimal self-contained runtime vendored by the Foldseek Claude plugin.

import { execFileSync } from 'node:child_process';
import fs from 'node:fs/promises';
import os from 'node:os';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { build } from 'esbuild';

const HERE = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(HERE, '../..');
const sourcePackage = JSON.parse(await fs.readFile(path.join(HERE, 'package.json'), 'utf8'));
const out = path.resolve(process.argv[2] ??
    path.join(HERE, 'dist', `foldseek-server-plugin-runtime-v${sourcePackage.version}.zip`));
const stage = await fs.mkdtemp(path.join(os.tmpdir(), 'foldseek-server-plugin-runtime-'));
const fixedTime = new Date('1980-01-01T00:00:00.000Z');

function packageName(input) {
    const marker = 'node_modules/';
    const at = input.lastIndexOf(marker);
    if (at === -1) return null;
    const parts = input.slice(at + marker.length).split('/');
    return parts[0].startsWith('@') ? parts.slice(0, 2).join('/') : parts[0];
}

async function thirdPartyNotices(inputs) {
    const names = [...new Set(inputs.map(packageName).filter(Boolean))].sort();
    const sections = ['# Third-party notices', '',
        'This file lists packages incorporated into `dist/server.mjs`.', ''];
    for (const name of names) {
        const dir = path.join(ROOT, 'node_modules', ...name.split('/'));
        const pkg = JSON.parse(await fs.readFile(path.join(dir, 'package.json'), 'utf8'));
        const licenseName = (await fs.readdir(dir)).find((entry) => /^(?:licen[cs]e|copying)(?:\..*)?$/i.test(entry));
        if (!licenseName) throw new Error(`${name} has no license file`);
        const license = (await fs.readFile(path.join(dir, licenseName), 'utf8')).trim();
        const repository = typeof pkg.repository === 'string' ? pkg.repository : pkg.repository?.url;
        sections.push(`## ${pkg.name} ${pkg.version}`, '', `License: ${pkg.license ?? 'see text below'}`);
        if (repository) sections.push(`Source: ${repository.replace(/^git\+/, '')}`);
        sections.push('', '```text', license, '```', '');
    }
    return `${sections.join('\n')}\n`;
}

try {
    await fs.mkdir(path.join(stage, 'scripts'), { recursive: true });
    await fs.mkdir(path.join(stage, 'dist'), { recursive: true });

    const result = await build({
        entryPoints: [path.join(HERE, 'src', 'server.js')],
        outfile: path.join(stage, 'dist', 'server.mjs'),
        bundle: true,
        platform: 'node',
        format: 'esm',
        target: 'node18',
        banner: { js: '// Generated by pack-plugin-runtime.mjs — do not edit.' },
        legalComments: 'eof',
        metafile: true,
        logLevel: 'warning',
    });

    await fs.copyFile(path.join(HERE, 'bin', 'foldseek-server-mcp.js'),
        path.join(stage, 'scripts', 'foldseek-server-mcp.js'));
    await fs.copyFile(path.join(ROOT, 'LICENSE'), path.join(stage, 'LICENSE'));
    await fs.writeFile(path.join(stage, 'THIRD_PARTY_NOTICES.md'),
        await thirdPartyNotices(Object.keys(result.metafile.inputs)));
    await fs.writeFile(path.join(stage, 'package.json'), `${JSON.stringify({
        name: sourcePackage.name,
        version: sourcePackage.version,
        private: true,
        description: sourcePackage.description,
        license: sourcePackage.license,
        type: 'module',
        bin: { 'foldseek-server-mcp': 'scripts/foldseek-server-mcp.js' },
        engines: sourcePackage.engines,
    }, null, 2)}\n`);

    const files = [
        'LICENSE',
        'THIRD_PARTY_NOTICES.md',
        'scripts/foldseek-server-mcp.js',
        'dist/server.mjs',
        'package.json',
    ];
    for (const relative of files) {
        const file = path.join(stage, relative);
        await fs.chmod(file, relative.startsWith('scripts/') ? 0o755 : 0o644);
        await fs.utimes(file, fixedTime, fixedTime);
    }

    await fs.mkdir(path.dirname(out), { recursive: true });
    await fs.rm(out, { force: true });
    execFileSync('zip', ['-X', '-q', out, ...files], {
        cwd: stage,
        env: { ...process.env, TZ: 'UTC' },
        stdio: ['ignore', 'ignore', 'inherit'],
    });
    process.stderr.write(`${out}  ${await fs.stat(out).then((stat) => stat.size)} bytes\n`);
} finally {
    await fs.rm(stage, { recursive: true, force: true });
}
